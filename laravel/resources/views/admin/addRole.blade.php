            data: formData,
            success: function(response){
                // Handle success response
                $('.add').hide();
                console.log(response); // Display response message
                if (response) {
                    // Clear form
                     Swal.fire({
                            icon: 'success',
                            title: 'Success!',
                            text: response.message,
                            showConfirmButton: false,
                            timer: 2000 // Automatically close after 1.5 seconds
                          });
                     
