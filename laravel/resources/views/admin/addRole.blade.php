                    data: {userId: userId},
                    success: function(response){
                      $('tbody #'+userId).remove();
                        Swal.fire({
                            icon: 'success',
                            title: 'Success!',
                            text: response.trim(),
                            showConfirmButton: false,
                            timer: 2000 // Automatically close after 1.5 seconds
                          });

                    },
